use crate::data_chunk::VectorCollection;
use crate::logical_type::{LogicalType, LogicalTypeID};
use crate::{
    Result,
    vector::{VectorReader, VectorWriter},
};

/// Describes validation and decoding for a DuckDB logical type.
/// Validation establishes the storage layout for both readers and writers.
///
/// Named struct readers can be derived for both `T` and `Option<T>` fields.
/// Use `AsDuckDB` to also derive logical types, owned value conversions, and typed writes:
///
/// ```
/// use duckdb_neo::{AsDuckDB, Result, vector::Vector};
///
/// #[derive(AsDuckDB)]
/// struct Record {
///     id: Option<i32>,
/// }
///
/// fn id<'a>(vector: &'a Vector<'_, Record>) -> Result<Option<&'a i32>> {
///     Ok(vector.reader()?.get(0)?.and_then(|row| row.id))
/// }
/// ```
///
/// The borrowed projection keeps every field nullable, even when the Rust input field is required.
///
/// Derived rows borrow the vector and prevent mutation while in use:
///
/// ```compile_fail,E0502
/// use duckdb_loadable_macros::AsVectorElement;
/// use duckdb_neo::{Result, vector::Vector};
///
/// #[derive(AsVectorElement)]
/// struct Record {
///     id: Option<i32>,
/// }
///
/// fn resize(vector: &mut Vector<'_, Record>) -> Result<()> {
///     let row = vector.reader()?.get(0)?.unwrap();
///     vector.set_size(10)?;
///     let _ = row.id;
///     Ok(())
/// }
/// ```
///
/// # Safety
///
/// Vector accessors trust the implementation:
///
/// - `Internal<'a>` must match DuckDB's physical layout for every lifetime and logical type `validate` accepts.
/// - `get` must only read within the vector's view and the children `validate` checked.
/// - If `WritableVectorElement` or `OwnedVectorElement` is implemented, `validate` must establish its writer's layout,
///   including child types and field order. This includes writers generated by `AsWritableVectorElement`.
///
/// A safe implementation is rejected:
///
/// ```compile_fail,E0200
/// # use duckdb_neo::{logical_type::LogicalTypeID, vector::{VectorReader, VectorElement}};
/// struct Wide([u64; 4]);
///
/// impl VectorElement for Wide {
///     const TYPE_ID: LogicalTypeID = LogicalTypeID::Integer;
///     type Internal<'a> = Wide;
///     type Ref<'a> = ();
///
///     unsafe fn get<'a, U: VectorElement>(_: &VectorReader<'a, U>, _: usize, _: usize) -> Self::Ref<'a>
///     where
///         Self: 'a,
///     {
///     }
/// }
/// ```
pub unsafe trait VectorElement: Sized {
    /// The DuckDB logical type represented by this Rust type.
    const TYPE_ID: LogicalTypeID;

    /// Physical entries exposed by [`VectorReader::as_slice`](crate::vector::VectorReader::as_slice).
    /// Use `()` when the element does not expose a physical representation.
    /// The lifetime bounds any storage referenced by an entry.
    type Internal<'a>;

    /// The borrowed or owned value returned for one vector row.
    type Ref<'a>
    where
        Self: 'a;

    /// Check the logical type and nested children when attaching this element type to a vector.
    /// A successful check must establish the layout for both reading and writing.
    /// `Ok(false)` means a type mismatch; `Err` means validation failed.
    fn validate(other: &LogicalType, children: Option<&VectorCollection>) -> Result<bool> {
        let _ = children;
        Ok(other.id()? == Self::TYPE_ID)
    }

    /// Borrow a value at its physical and logical indexes.
    ///
    /// Prefer [`VectorReader::get`](crate::vector::VectorReader::get) or
    /// [`VectorReader::iter`](crate::vector::VectorReader::iter), which uphold these requirements.
    ///
    /// # Safety
    ///
    /// - `reader` must have been validated as `Self`, with its descendants prepared.
    /// - `logical` must be a row of `reader`, `physical` its physical index, and the row must not be `NULL`.
    ///
    /// ```compile_fail,E0133
    /// # use duckdb_neo::vector::{Vector, VectorElement};
    /// fn read<'a>(vector: &'a Vector<'_, i8>) -> &'a i64 {
    ///     let reader = vector.reader().unwrap();
    ///     <i64 as VectorElement>::get(&reader, 10_000, 0)
    /// }
    /// ```
    unsafe fn get<'a, U: VectorElement>(reader: &VectorReader<'a, U>, physical: usize, logical: usize) -> Self::Ref<'a>
    where
        Self: 'a;
}

/// Marks vector elements backed by DuckDB's byte storage and arena.
///
/// Implemented for [`String`], [`UncheckedString`](crate::types::UncheckedString),
/// [`BlobValue`](crate::types::BlobValue), [`BitValue`](crate::types::BitValue),
/// [`BigNum`](crate::types::BigNum), and [`BigNumValue`](crate::types::BigNumValue).
///
/// Non-byte vectors do not expose an arena:
///
/// ```compile_fail,E0599
/// use duckdb_neo::vector::Vector;
///
/// fn arena(vector: &mut Vector<'_, i32>) -> duckdb_neo::Result<()> {
///     let _ = vector.writer()?.arena();
///     Ok(())
/// }
/// ```
pub trait HasDuckDBBytes: VectorElement {}

/// Adds a supported output representation to a readable vector element.
///
/// `AsDuckDB` uses the struct itself as the write input, without a separate projection:
///
/// ```
/// use duckdb_neo::{AsDuckDB, Result, vector::Vector};
///
/// #[derive(AsDuckDB)]
/// struct Record {
///     name: String,
///     value: Option<i32>,
/// }
///
/// fn write(vector: &mut Vector<'_, Record>) -> Result<()> {
///     vector.writer()?.set(0, Some(Record { name: "duck".to_owned(), value: Some(42) }))
/// }
/// ```
///
/// `Option<T>` fields preserve NULLs; plain fields write non-NULL values. Passing
/// `None` to the writer nulls the whole struct and its descendants, without requiring
/// `Default`. Owned strings and containers are moved, not cloned. Write inputs with
/// borrowed fields cannot outlive their data:
///
/// ```compile_fail,E0515
/// use duckdb_loadable_macros::{AsVectorElement, AsWritableVectorElement};
///
/// #[derive(AsVectorElement, AsWritableVectorElement)]
/// struct Record<'a> {
///     name: &'a str,
/// }
///
/// fn dangling<'a>() -> Record<'a> {
///     let name = String::from("duck");
///     Record { name: &name }
/// }
/// ```
///
/// # Safety
///
/// `write` must only write valid values of the vector's logical type, since
/// DuckDB and the readers trust what is stored. It may rely on the layout checked
/// by [`VectorElement::validate`], but must enforce value-dependent constraints.
pub unsafe trait WritableVectorElement: VectorElement {
    /// The input accepted when writing one row; `'a` bounds any data it borrows.
    type Write<'a>;

    /// Encode one value into a writable vector.
    ///
    /// [`VectorWriter::set`](crate::vector::VectorWriter::set) and
    /// [`VectorWriter::set_unchecked`](crate::vector::VectorWriter::set_unchecked)
    /// maintain the row's validity after
    /// successful encoding. Nested NULL values must still propagate to descendants,
    /// and value-API writers preserve cast nullness.
    ///
    /// Prefer [`VectorWriter::set`](crate::vector::VectorWriter::set), which upholds these requirements.
    ///
    /// # Safety
    ///
    /// - `index` must be less than [`VectorWriter::len`].
    ///
    /// ```compile_fail,E0133
    /// # use duckdb_neo::vector::{Vector, WritableVectorElement};
    /// fn write(vector: &mut Vector<'_, i32>) -> duckdb_neo::Result<()> {
    ///     <i32 as WritableVectorElement>::write(&mut vector.writer()?, 0, Some(1))
    /// }
    /// ```
    unsafe fn write(writer: &mut VectorWriter<'_, Self>, index: usize, value: Option<Self::Write<'_>>) -> Result<()>;
}

/// Writes owned Rust fields without constructing an intermediate DuckDB value.
///
/// Types whose native write input is `Self` implement this automatically. Types
/// such as `String` borrow their native input for the duration of the write.
///
/// # Safety
/// Implementations must uphold `VectorElement::validate`, initialize non-NULL
/// values, and update validity, including NULL descendants of nested values.
pub unsafe trait OwnedVectorElement: VectorElement {
    /// Write an owned value and its validity into an already-validated row.
    ///
    /// # Safety
    /// `index` must be less than `writer.len()`.
    unsafe fn write_owned(writer: &mut VectorWriter<'_, Self>, index: usize, value: Option<Self>) -> Result<()>;
}

// SAFETY: the native writer accepts the same value and maintains its validity.
unsafe impl<T> OwnedVectorElement for T
where
    T: for<'a> WritableVectorElement<Write<'a> = T>,
{
    #[inline]
    unsafe fn write_owned(writer: &mut VectorWriter<'_, Self>, index: usize, value: Option<Self>) -> Result<()> {
        unsafe { writer.set_unchecked(index, value) }
    }
}

/// The element type has not been checked against the vector's logical type yet.
#[derive(Debug, Clone)]
pub struct Unknown;

// SAFETY: `Internal` is zero-sized and `get` reads nothing.
unsafe impl VectorElement for Unknown {
    const TYPE_ID: LogicalTypeID = LogicalTypeID::Unknown;

    type Ref<'a> = ();

    type Internal<'a> = ();

    fn validate(_other: &LogicalType, _children: Option<&VectorCollection>) -> Result<bool> {
        Ok(true)
    }

    unsafe fn get<'a, U: VectorElement>(
        _reader: &VectorReader<'a, U>,
        _physical: usize,
        _logical: usize,
    ) -> Self::Ref<'a>
    where
        Self: 'a,
    {
    }
}
